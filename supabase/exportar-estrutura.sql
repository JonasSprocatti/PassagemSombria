-- ============================================================================
--  Exporta a estrutura do schema `passagem` (tabelas, chaves, índices, RLS,
--  políticas, funções, gatilhos e permissões de coluna) como comandos SQL.
--
--  Só LÊ, não muda nada. Rodar no SQL Editor do projeto e baixar o resultado
--  (botão "Export" / "Download CSV"). Serve para manter supabase/base.sql
--  igual ao banco de verdade.
--
--  Não exporta dados nem contas de login.
-- ============================================================================
with s as (select 'passagem'::regnamespace as ns),
cmds as (
  -- 10: tipos enum
  select 10 as fase, t.typname::text as obj, format('create type passagem.%I as enum (%s);', t.typname,
         (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)) as comando
  from pg_type t, s where t.typnamespace = s.ns and t.typtype = 'e'

  -- 20: tabelas
  union all
  select 20, c.relname, format(E'create table passagem.%I (\n  %s\n);', c.relname,
    (select string_agg(
       format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
       || case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid)) else '' end
       || case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end
       || case when ad.adbin is not null and a.attgenerated = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
       || case when a.attnotnull then ' not null' else '' end,
       E',\n  ' order by a.attnum)
     from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
     where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped))
  from pg_class c, s where c.relnamespace = s.ns and c.relkind = 'r' and c.relname not like '\_mig\_%'

  -- 30: chaves primárias, únicas, checks e estrangeiras
  union all
  select case when k.contype = 'f' then 31 else 30 end, c.relname,
         format('alter table passagem.%I add constraint %I %s;', c.relname, k.conname, pg_get_constraintdef(k.oid))
  from pg_constraint k join pg_class c on c.oid = k.conrelid, s
  where c.relnamespace = s.ns and k.contype in ('p', 'u', 'c', 'f', 'x') and c.relname not like '\_mig\_%'

  -- 40: índices que não são de constraint
  union all
  select 40, c.relname, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join pg_class c on c.oid = i.indrelid, s
  where c.relnamespace = s.ns and c.relname not like '\_mig\_%'
    and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)

  -- 50: funções
  union all
  select 50, p.proname, pg_get_functiondef(p.oid) || ';'
  from pg_proc p, s
  where p.pronamespace = s.ns and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')

  -- 60: RLS ligada
  union all
  select 60, c.relname, format('alter table passagem.%I enable row level security;', c.relname)
  from pg_class c, s where c.relnamespace = s.ns and c.relkind = 'r' and c.relrowsecurity and c.relname not like '\_mig\_%'

  -- 70: políticas de RLS
  union all
  select 70, c.relname, format('create policy %I on passagem.%I as %s for %s to %s%s%s;',
    p.polname, c.relname,
    case when p.polpermissive then 'permissive' else 'restrictive' end,
    case p.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
    coalesce((select string_agg(case when r = 0 then 'public' else quote_ident(pg_get_userbyid(r)) end, ', ') from unnest(p.polroles) r), 'public'),
    coalesce(E'\n  using (' || pg_get_expr(p.polqual, p.polrelid) || ')', ''),
    coalesce(E'\n  with check (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', ''))
  from pg_policy p join pg_class c on c.oid = p.polrelid, s
  where c.relnamespace = s.ns

  -- 80: gatilhos nas tabelas do jogo e em auth.users que chamam funções do jogo
  union all
  select 80, c.relname, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t join pg_class c on c.oid = t.tgrelid, s
  where c.relnamespace = s.ns and not t.tgisinternal
  union all
  select 80, 'auth.users', pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t join pg_proc p on p.oid = t.tgfoid, s
  where t.tgrelid = 'auth.users'::regclass and not t.tgisinternal and p.pronamespace = s.ns

  -- 90: permissões por coluna (UPDATE só em algumas colunas, etc.)
  union all
  select 90, c.relname, format('grant %s (%s) on passagem.%I to %I;', g.privilege_type, string_agg(quote_ident(g.column_name), ', '), c.relname, g.grantee)
  from information_schema.column_privileges g
  join pg_class c on c.relname = g.table_name and c.relnamespace = 'passagem'::regnamespace
  where g.table_schema = 'passagem' and g.grantee in ('anon', 'authenticated')
    and not exists (select 1 from information_schema.table_privileges tp
                    where tp.table_schema = g.table_schema and tp.table_name = g.table_name
                      and tp.grantee = g.grantee and tp.privilege_type = g.privilege_type)
  group by g.privilege_type, c.relname, g.grantee

  -- 95: tabelas no Realtime
  union all
  select 95, tablename::text, format('alter publication supabase_realtime add table passagem.%I;', tablename)
  from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'passagem'
)
select fase, obj, comando from cmds order by fase, obj, comando;
