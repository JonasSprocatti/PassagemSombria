-- ============================================================================
--  PASSO 1 — rodar no SQL Editor do projeto ANTIGO do Passagem Sombria.
--
--  Renomeia o schema `public` para `passagem` (tabelas, dados, políticas e
--  funções vão junto) e deixa preparado, dentro dele, tudo que o projeto novo
--  vai puxar sozinho no passo 2:
--    • _mig_ddl            — a estrutura do banco escrita como comandos SQL
--                            (tabelas, chaves, índices, políticas, funções…);
--    • _mig_users/identities — cópia das contas de login;
--    • _mig_gatilhos_auth  — gatilhos do jogo em auth.users (cadastro);
--    • _mig_realtime       — tabelas que estavam no Realtime.
--
--  Reversível: 9-desfazer-projeto-antigo.sql devolve o projeto como estava.
-- ============================================================================
begin;

do $$ begin
  if exists (select 1 from pg_namespace where nspname = 'passagem') then
    raise exception 'O passo 1 já foi feito neste projeto (o schema passagem já existe). Pode seguir para o passo 2, no projeto novo.';
  end if;
end $$;

alter schema public rename to passagem;
create schema public;
grant usage on schema public to postgres, anon, authenticated, service_role;
grant all on schema public to postgres, service_role;

-- Contas de login. Cópia temporária: o passo 3 apaga depois de usar.
create table passagem._mig_users      as select * from auth.users;
create table passagem._mig_identities as select * from auth.identities;

-- Gatilhos do jogo em auth.users (ex.: o que cria o perfil no cadastro).
-- Depois do rename, a definição já aponta para passagem.<função>.
create table passagem._mig_gatilhos_auth as
  select t.tgname::text as nome, pg_get_triggerdef(t.oid) as definicao
  from pg_trigger t
  where t.tgrelid = 'auth.users'::regclass and not t.tgisinternal;

-- Tabelas do jogo que estavam no Realtime.
create table passagem._mig_realtime as
  select tablename::text as tabela from pg_publication_tables
  where pubname = 'supabase_realtime' and schemaname = 'passagem';

-- Estrutura do banco como comandos, por fase (o passo 2 executa em ordem).
create table passagem._mig_ddl (fase int not null, ordem int not null, comando text not null);

-- 10: tipos enum
insert into passagem._mig_ddl
select 10, row_number() over (), format('create type passagem.%I as enum (%s)', t.typname,
         (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid))
from pg_type t where t.typnamespace = 'passagem'::regnamespace and t.typtype = 'e';

-- 20: sequências avulsas (as de coluna identity nascem com a tabela)
insert into passagem._mig_ddl
select 20, row_number() over (), format('create sequence passagem.%I as %s increment %s minvalue %s maxvalue %s start %s cache %s %s',
         c.relname, format_type(s.seqtypid, null), s.seqincrement, s.seqmin, s.seqmax, s.seqstart, s.seqcache,
         case when s.seqcycle then 'cycle' else 'no cycle' end)
from pg_class c join pg_sequence s on s.seqrelid = c.oid
where c.relnamespace = 'passagem'::regnamespace
  and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i');

-- 42: funções, depois das tabelas (o corpo é reescrito de public. para passagem. no passo 2)
insert into passagem._mig_ddl
select 42, row_number() over (), pg_get_functiondef(p.oid)
from pg_proc p
where p.pronamespace = 'passagem'::regnamespace and p.prokind in ('f', 'p')
  and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e');

-- 40: tabelas (colunas, tipos, padrões, NOT NULL, identity, colunas geradas)
insert into passagem._mig_ddl
select 40, row_number() over (), format('create table passagem.%I (%s)', c.relname,
  (select string_agg(
     format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
     || case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid)) else '' end
     || case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end
     || case when ad.adbin is not null and a.attgenerated = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
     || case when a.attnotnull then ' not null' else '' end,
     ', ' order by a.attnum)
   from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
   where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped))
from pg_class c
where c.relnamespace = 'passagem'::regnamespace and c.relkind = 'r' and c.relname <> '_mig_ddl';

-- 45: sequência "dona" de coluna (serial/bigserial)
insert into passagem._mig_ddl
select 45, row_number() over (), format('alter sequence passagem.%I owned by passagem.%I.%I', s.relname, t.relname, a.attname)
from pg_depend d
join pg_class s on s.oid = d.objid and s.relkind = 'S'
join pg_class t on t.oid = d.refobjid
join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
where d.deptype = 'a' and s.relnamespace = 'passagem'::regnamespace and t.relname <> '_mig_ddl';

-- 60/65: chaves primárias, únicas e checks; depois as estrangeiras
insert into passagem._mig_ddl
select case when k.contype = 'f' then 65 else 60 end, row_number() over (order by k.contype),
       format('alter table %s add constraint %I %s', k.conrelid::regclass, k.conname, pg_get_constraintdef(k.oid))
from pg_constraint k join pg_class c on c.oid = k.conrelid
where c.relnamespace = 'passagem'::regnamespace and k.contype in ('p', 'u', 'c', 'f', 'x') and c.relname <> '_mig_ddl';

-- 70: índices que não são de constraint
insert into passagem._mig_ddl
select 70, row_number() over (), pg_get_indexdef(i.indexrelid)
from pg_index i join pg_class c on c.oid = i.indrelid
where c.relnamespace = 'passagem'::regnamespace and c.relname <> '_mig_ddl'
  and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid);

-- 80: RLS ligada/forçada
insert into passagem._mig_ddl
select 80, row_number() over (), format('alter table passagem.%I enable row level security', c.relname)
from pg_class c where c.relnamespace = 'passagem'::regnamespace and c.relkind = 'r' and c.relrowsecurity;
insert into passagem._mig_ddl
select 80, 100000 + row_number() over (), format('alter table passagem.%I force row level security', c.relname)
from pg_class c where c.relnamespace = 'passagem'::regnamespace and c.relkind = 'r' and c.relforcerowsecurity;

-- 85: políticas de RLS
insert into passagem._mig_ddl
select 85, row_number() over (), format('create policy %I on %s as %s for %s to %s%s%s',
  p.polname, p.polrelid::regclass,
  case when p.polpermissive then 'permissive' else 'restrictive' end,
  case p.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
  coalesce((select string_agg(case when r = 0 then 'public' else quote_ident(pg_get_userbyid(r)) end, ', ') from unnest(p.polroles) r), 'public'),
  coalesce(' using (' || pg_get_expr(p.polqual, p.polrelid) || ')', ''),
  coalesce(' with check (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', ''))
from pg_policy p join pg_class c on c.oid = p.polrelid
where c.relnamespace = 'passagem'::regnamespace;

-- 90: gatilhos nas tabelas do jogo
insert into passagem._mig_ddl
select 90, row_number() over (), pg_get_triggerdef(t.oid)
from pg_trigger t join pg_class c on c.oid = t.tgrelid
where c.relnamespace = 'passagem'::regnamespace and not t.tgisinternal;

-- 95: views (se houver)
insert into passagem._mig_ddl
select 95, row_number() over (), format('create view passagem.%I as %s', c.relname, pg_get_viewdef(c.oid))
from pg_class c where c.relnamespace = 'passagem'::regnamespace and c.relkind = 'v';

-- 99: posição atual de cada sequência
do $$
declare s record; v bigint; chamado boolean;
begin
  for s in select c.relname from pg_class c where c.relnamespace = 'passagem'::regnamespace and c.relkind = 'S' loop
    execute format('select last_value, is_called from passagem.%I', s.relname) into v, chamado;
    insert into passagem._mig_ddl values (99, 0, format('select setval(%L, %s, %s)', 'passagem.' || quote_ident(s.relname), v, chamado::text));
  end loop;
end $$;

commit;

-- Deve voltar VAZIO. Se aparecer alguma extensão aqui, ela estava instalada
-- no public e não vai junto — pare e avise antes de seguir.
select e.extname as extensao_no_schema from pg_extension e
  join pg_namespace n on n.oid = e.extnamespace where n.nspname = 'passagem';

-- Confira: quantos comandos de estrutura foram gerados por fase.
select fase, count(*) from passagem._mig_ddl group by fase order by fase;
